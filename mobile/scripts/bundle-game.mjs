// Builds the web game (the repo root) for the phone app and packs it into
// mobile/game/ so Metro bundles every file into the app as an asset.
//
//   node scripts/bundle-game.mjs
//
// Runs on its own before `npm start` and on EAS (eas-build-post-install).
// mobile/game/ is generated, so it's not committed.
import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const mobile = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(mobile, '..');
const built = join(root, 'dist-app');
const out = join(mobile, 'game');
const files = join(out, 'files');
// Every game file gets this extension so Metro treats it as a plain asset
// (it would try to compile .js). The app strips it again on the device.
const EXT = '.gamefile';

const run = (cmd) => execSync(cmd, { cwd: root, stdio: 'inherit' });
if (!existsSync(join(root, 'node_modules'))) run('npm ci');
run('npm run build:app');

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

rmSync(out, { recursive: true, force: true });
const hash = createHash('sha256');
const entries = [];
for (const src of walk(built).sort()) {
  const rel = relative(built, src).split('\\').join('/');
  const dest = join(files, rel + EXT);
  mkdirSync(dirname(dest), { recursive: true });
  cpSync(src, dest);
  hash.update(rel).update(readFileSync(src));
  entries.push(`  [${JSON.stringify(rel)}, require(${JSON.stringify('./files/' + rel + EXT)})],`);
}

writeFileSync(
  join(out, 'manifest.ts'),
  `// Generated by scripts/bundle-game.mjs. Don't edit.
export const GAME_VERSION = ${JSON.stringify(hash.digest('hex').slice(0, 16))};
export const GAME_FILES: [path: string, asset: number][] = [
${entries.join('\n')}
];
`,
);
console.log(`Packed ${entries.length} game files into mobile/game/`);
